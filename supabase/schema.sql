create or replace function public.batch_register(p_session_id bigint,p_games jsonb) returns jsonb
language plpgsql security invoker set search_path=public as $$
declare item jsonb; created_n int:=0; skipped_n int:=0; batch_n int:=0; errors_n int:=0; sig text; seen text[]:='{}';
 team_a_ids bigint[]; team_b_ids bigint[]; score_a_num int; score_b_num int; canonical_a bigint[]; canonical_b bigint[]; canonical_score_a int; canonical_score_b int;
begin
 if auth.uid() is null then raise exception 'authentication required'; end if;
 for item in select value from jsonb_array_elements(coalesce(p_games,'[]'::jsonb)) loop
  begin
   select array_agg(x order by x) into team_a_ids from unnest(array[(item->>'a1')::bigint,(item->>'a2')::bigint]) x;
   select array_agg(x order by x) into team_b_ids from unnest(array[(item->>'b1')::bigint,(item->>'b2')::bigint]) x;
   score_a_num:=(item->>'score_a')::int; score_b_num:=(item->>'score_b')::int;
   if team_a_ids<=team_b_ids then canonical_a:=team_a_ids; canonical_b:=team_b_ids; canonical_score_a:=score_a_num; canonical_score_b:=score_b_num;
   else canonical_a:=team_b_ids; canonical_b:=team_a_ids; canonical_score_a:=score_b_num; canonical_score_b:=score_a_num; end if;
   sig:='[['||array_to_string(canonical_a,',')||'],['||array_to_string(canonical_b,',')||']]|'||canonical_score_a||'|'||canonical_score_b;
   if sig=any(seen) then batch_n:=batch_n+1; continue; end if; seen:=array_append(seen,sig);
   if exists(select 1 from public.games g where g.session_id=p_session_id and (
     ((select array_agg(gp.member_id order by gp.member_id) from public.game_players gp where gp.game_id=g.id and gp.team='A')=team_a_ids and
      (select array_agg(gp.member_id order by gp.member_id) from public.game_players gp where gp.game_id=g.id and gp.team='B')=team_b_ids and g.team_a_score=score_a_num and g.team_b_score=score_b_num)
     or
     ((select array_agg(gp.member_id order by gp.member_id) from public.game_players gp where gp.game_id=g.id and gp.team='A')=team_b_ids and
      (select array_agg(gp.member_id order by gp.member_id) from public.game_players gp where gp.game_id=g.id and gp.team='B')=team_a_ids and g.team_a_score=score_b_num and g.team_b_score=score_a_num)
   )) then skipped_n:=skipped_n+1; continue; end if;
   perform public.create_game(p_session_id,coalesce(item->>'team_a_name','A팀'),coalesce(item->>'team_b_name','B팀'),array[(item->>'a1')::bigint,(item->>'a2')::bigint],array[(item->>'b1')::bigint,(item->>'b2')::bigint],(item->>'score_a')::smallint,(item->>'score_b')::smallint,item->>'comment');
   created_n:=created_n+1;
  exception when others then errors_n:=errors_n+1;
  end;
 end loop;
 return jsonb_build_object('message',created_n||'건 저장 (중복 '||(skipped_n+batch_n)||'건 제외)','created_count',created_n,'skipped_duplicate_count',skipped_n,'batch_duplicate_count',batch_n,'error_count',errors_n);
end $$;
grant execute on function public.batch_register(bigint,jsonb) to authenticated;

