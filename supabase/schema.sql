-- Prevent direct changes to the active flag except through an admin-authorized operation.
create or replace function public.guard_member_active_change() returns trigger
language plpgsql security invoker set search_path=public as $$ begin
 if tg_op='INSERT' then
  if (new.is_active is distinct from true or new.is_admin is distinct from false) and not public.is_admin() then
   raise exception 'admin required to set member admin or active status';
  end if;
 elsif (new.is_active is distinct from old.is_active or new.is_admin is distinct from old.is_admin) and not public.is_admin() then
  raise exception 'admin required to change member admin or active status';
 end if;
 return new;
end $$;
drop trigger if exists members_guard_active on public.members;
create trigger members_guard_active before insert or update on public.members
for each row execute function public.guard_member_active_change();

