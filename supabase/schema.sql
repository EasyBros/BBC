create or replace view public.v_game_players with (security_invoker = true) as
select gp.game_id,g.session_id,s.date,g.played_at,gp.team,gp.member_id,
       g.team_a_score,g.team_b_score,g.winner_team,g.team_a_name,g.team_b_name,g.comment
from public.game_players gp join public.games g on g.id=gp.game_id
join public.sessions s on s.id=g.session_id;

create or replace function public.is_admin() returns boolean
language sql stable security invoker set search_path=public
as $$ select exists(select 1 from public.app_admins a where a.user_id=auth.uid()) $$;

