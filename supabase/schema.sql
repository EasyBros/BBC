create extension if not exists pgcrypto;

create table if not exists public.members (
  id bigint generated by default as identity primary key,
  name text not null,
  nickname text,
  league smallint not null default 1 check (league in (1,2)),
  joined_at date not null default current_date,
  is_admin boolean not null default false,
  is_guest boolean not null default false,
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);
create table if not exists public.seasons (
  id bigint generated by default as identity primary key,
  year integer not null,
  kind text not null check (kind in ('spring','summer','autumn','winter')),
  name text not null,
  start_date date not null,
  end_date date not null,
  is_active boolean not null default false,
  created_at timestamptz not null default now(),
  check (start_date <= end_date), unique(year,kind)
);
create table if not exists public.sessions (
  id bigint generated by default as identity primary key,
  date date not null unique,
  location text,
  note text,
  created_at timestamptz not null default now()
);
create table if not exists public.attendance (
  session_id bigint not null references public.sessions(id) on delete cascade,
  member_id bigint not null references public.members(id),
  created_at timestamptz not null default now(),
  primary key(session_id,member_id)
);
create table if not exists public.games (
  id bigint generated by default as identity primary key,
  session_id bigint not null references public.sessions(id) on delete cascade,
  team_a_name text not null default 'A팀',
  team_b_name text not null default 'B팀',
  team_a_score smallint not null check (team_a_score between 0 and 30),
  team_b_score smallint not null check (team_b_score between 0 and 30),
  winner_team char(1) generated always as (case when team_a_score > team_b_score then 'A' else 'B' end) stored,
  comment text check (comment is null or char_length(comment) <= 200),
  played_at timestamptz not null default now(),
  check (team_a_score <> team_b_score)
);
create table if not exists public.game_players (
  game_id bigint not null references public.games(id) on delete cascade,
  member_id bigint not null references public.members(id),
  team char(1) not null check (team in ('A','B')),
  primary key(game_id,member_id)
);
create table if not exists public.notices (
  id bigint generated by default as identity primary key,
  title text not null,
  content text not null default '',
  author text not null default '',
  is_pinned boolean not null default false,
  is_popup boolean not null default false,
  league smallint check (league is null or league in (1,2)),
  created_at timestamptz not null default now()
);
create table if not exists public.settings (
  key text primary key,
  value jsonb not null
);
create table if not exists public.app_admins (
  user_id uuid primary key references auth.users(id) on delete cascade
);
