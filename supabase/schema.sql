create or replace function public.ensure_session(p_date date) returns public.sessions
language plpgsql security invoker set search_path=public as $$ declare r public.sessions; begin
 if auth.uid() is null then raise exception 'authentication required'; end if;
 insert into public.sessions(date) values(p_date) on conflict(date) do nothing;
 select * into r from public.sessions where date=p_date; return r;
end $$;

grant execute on function public.ensure_session(date) to authenticated;

create or replace function public.set_attendance(p_session_id bigint,p_member_ids bigint[]) returns timestamptz
language plpgsql security definer set search_path=public as $$ declare latest timestamptz; begin
 if auth.uid() is null then raise exception 'authentication required'; end if;
 delete from public.attendance where session_id=p_session_id and not (member_id=any(coalesce(p_member_ids,'{}')));
 insert into public.attendance(session_id,member_id)
 select p_session_id,x from unnest(coalesce(p_member_ids,'{}')) x on conflict(session_id,member_id) do nothing;
 select max(created_at) into latest from public.attendance where session_id=p_session_id; return latest;
end $$;
grant execute on function public.set_attendance(bigint,bigint[]) to authenticated;

create or replace function public.create_game(p_session_id bigint,p_team_a_name text,p_team_b_name text,p_team_a bigint[],p_team_b bigint[],p_score_a smallint,p_score_b smallint,p_comment text default null) returns jsonb
language plpgsql security definer set search_path=public as $$ declare gid bigint; ids bigint[]; begin
 if auth.uid() is null then raise exception 'authentication required'; end if;
 if cardinality(p_team_a)<>2 or cardinality(p_team_b)<>2 then raise exception 'each team needs two players'; end if;
 ids:=p_team_a||p_team_b;
 if (select count(distinct x) from unnest(ids) x)<>4 then raise exception 'players must be distinct'; end if;
 insert into public.games(session_id,team_a_name,team_b_name,team_a_score,team_b_score,comment)
 values(p_session_id,coalesce(nullif(p_team_a_name,''),'A팀'),coalesce(nullif(p_team_b_name,''),'B팀'),p_score_a,p_score_b,p_comment) returning id into gid;
 insert into public.game_players(game_id,member_id,team) select gid,x,'A' from unnest(p_team_a) x;
 insert into public.game_players(game_id,member_id,team) select gid,x,'B' from unnest(p_team_b) x;
 return jsonb_build_object('id',gid);
end $$;
grant execute on function public.create_game(bigint,text,text,bigint[],bigint[],smallint,smallint,text) to authenticated;

create or replace function public.update_game(p_game_id bigint,p_session_id bigint,p_team_a_name text,p_team_b_name text,p_team_a bigint[],p_team_b bigint[],p_score_a smallint,p_score_b smallint,p_comment text default null) returns jsonb
language plpgsql security definer set search_path=public as $$ declare ids bigint[]; begin
 if auth.uid() is null then raise exception 'authentication required'; end if;
 if cardinality(p_team_a)<>2 or cardinality(p_team_b)<>2 then raise exception 'each team needs two players'; end if;
 ids:=p_team_a||p_team_b;
 if (select count(distinct x) from unnest(ids) x)<>4 then raise exception 'players must be distinct'; end if;
 update public.games set session_id=p_session_id,team_a_name=p_team_a_name,team_b_name=p_team_b_name,team_a_score=p_score_a,team_b_score=p_score_b,comment=p_comment where id=p_game_id;
 if not found then raise exception 'game not found'; end if;
 delete from public.game_players where game_id=p_game_id;
 insert into public.game_players(game_id,member_id,team) select p_game_id,x,'A' from unnest(p_team_a) x;
 insert into public.game_players(game_id,member_id,team) select p_game_id,x,'B' from unnest(p_team_b) x;
 return jsonb_build_object('id',p_game_id);
end $$;
